import time

import yolo_lib as Y
import config

# ══════════════════════════════════════════════════════════════════
#  ค่าที่ปรับได้ของขั้นนี้
# ══════════════════════════════════════════════════════════════════

BENCH_ROUNDS = 5     # วัดความเร็วกี่รอบแล้วเอามาเฉลี่ย

# ══════════════════════════════════════════════════════════════════
#  ตั้งแต่บรรทัดนี้ลงไปคือส่วนทำงาน
# ══════════════════════════════════════════════════════════════════


def main():
    print("\n  ── ขั้นที่ 1 · ตรวจว่าโมเดลใช้งานได้ ──")
    print("  ไฟล์โมเดล: %s" % Y.here(config.MODEL_PATH))
    print("  ค่าที่ตั้งไว้: conf=%.2f  iou=%.2f  imgsz=%d"
          % (config.CONF, config.IOU, config.IMGSZ))

    model = Y.load_model()

    # วัดความเร็วจริงของเครื่องนี้ ด้วยภาพเปล่าขนาดเท่าที่โมเดลรับ
    print("\n  กำลังวัดความเร็ว... (warm-up ก่อน 2 รอบ)")
    Y.warmup(model)

    import numpy as np
    blank = np.zeros((config.IMGSZ, config.IMGSZ, 3), dtype=np.uint8)

    times = []
    for _ in range(BENCH_ROUNDS):
        t0 = time.time()
        model(blank, size=config.IMGSZ)
        times.append((time.time() - t0) * 1000)

    avg = sum(times) / len(times)
    print("\n  ผลที่วัดได้จากเครื่องนี้")
    print("    ตัวประมวลผล   %s" % model.device_name.upper())
    print("    เวลาต่อเฟรม   %.0f ms" % avg)
    print("    ความเร็ว      %.1f FPS" % (1000.0 / avg))

    if avg > 200:
        print("\n  ช้ากว่าที่ควรเป็น — ถ้าอยากเร่ง ให้ลด IMGSZ ใน config.py")
        print("  เป็น 416 หรือ 320 แล้วรันไฟล์นี้ใหม่เพื่อเทียบตัวเลข")

    print("\n  ผ่านแล้ว — ต่อไปกด Run ที่ step2_image.py\n")


if __name__ == "__main__":
    main()
